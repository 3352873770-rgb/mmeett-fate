export function classicsByCat(cat: string | 'all'): Classic[] {
  return cat === 'all' ? classics : classics.filter((c) => c.cat === cat)
}

export function classicByTitle(title: string): Classic | undefined {
  const decoded = decodeURIComponent(title)
  return classics.find((c) => c.title === decoded || c.id === decoded)
}

export function getClassicQuotes(book: Classic): ClassicQuote[] {
  if (book.quotes?.length) return book.quotes
  const [a, b] = book.paragraphs
  return [
    {
      classic: a.split('。')[0] + '。',
      vernacular: a,
      usage: `用于${book.tools.replace(/^对应/, '')}时，先按「${book.topics}」来对照读。`,
    },
    {
      classic: b.split('。')[0] + '。',
      vernacular: b,
      usage: `回到工具核盘时，先看主线，再落到所问，不拿单句断语替代全局。`,
    },
  ]
}

export function classicCatCount(cat: string): number {
  return classics.filter((c) => c.cat === cat).length
}

